// ST-6.7: runs the crash matrix (mod tests) and the storage SIGKILL test, and writes docs/done/evidence/m0-m7/m5-crash/crash-matrix.md.
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const out = resolve(root, '../docs/done/evidence/m0-m7/m5-crash')
const mod = spawnSync('claude', ['plugin', 'test', '.'], { cwd: root, encoding: 'utf8' })
const lines = `${mod.stdout}\n${mod.stderr}`.split('\n').filter(l => /\((pass|fail)\) AC-16 crash point/.test(l))
const env = { ...process.env }
delete env.NODE_TEST_CONTEXT
const unit = spawnSync(process.execPath, ['--test', '--experimental-strip-types', '--no-warnings', 'tests/unit/crash.spec.ts'], { cwd: root, encoding: 'utf8', env })
const unitOk = unit.status === 0
const passed = lines.filter(l => l.includes('(pass)')).length
const all = passed > 0 && passed === lines.length
const version = execFileSync('claude', ['--version'], { encoding: 'utf8' }).trim()
const row = l => {
  const m = /\((pass|fail)\) AC-16 crash point "([^"]+)".*?\[([\d.]+)ms\]/.exec(l)
  return m ? `| ${m[2]} | ${m[1].toUpperCase()} | ${m[3]} ms |` : `| ? | ${l.trim()} | |`
}
const md = [
  `# Crash matrix (AC-16, ST-6.7): ${passed}/${lines.length}${all && unitOk ? ' PASS' : ' FAIL'}`, '',
  `Generated by \`npm run crash:report\` on ${new Date().toISOString().slice(0, 10)} · Claude Code ${version} · node ${process.version}`, '',
  'Each point: the plugin stops dead there (`JEEVES_TEST=1 JEEVES_TEST_CRASH=<point>`; it logs `jeeves: crash point <point>` and never returns). A new session starts, waits out the dead lock (121 s on the mock clock) and types `/jeeves recover`. Asserted: the state the dead process left (02 §8), exactly one continuation after all timers of both sessions ran, no handover file written twice, the continuation built from the handover the dead process saved (hash equal) or, with none saved, the gap note, and a second `/jeeves recover` refused.', '',
  '| Point | Result | Time |', '|---|---|---|', ...lines.map(row), '',
  '| Point | Left on disk | Recovered from |', '|---|---|---|',
  '| threshold | ROTATION_REQUESTED | no handover yet, gap note |',
  '| mid-handover | HANDOVER_GENERATING | no handover yet, gap note |',
  '| after-persist | VALIDATING + handover-001.md | handover-001 adopted, no gap |',
  '| before-clear | ROTATING | handover-001, no gap |',
  '| before-inject | ROTATING (step CLEARED, old session ended) | handover-001, no gap |',
  '| before-submit | RESTORING | handover-001, no gap |', '',
  `Storage layer (P): \`tests/unit/crash.spec.ts\` (SIGKILL at random points of the atomic state swap, 25 rounds): ${unitOk ? 'PASS' : 'FAIL'}.`, '',
  'Source: `tests/mod/crash.test.ts`. The live demo (a real process killed mid-rotation) is in `../m5-demo/`.', '',
].join('\n')
mkdirSync(out, { recursive: true })
writeFileSync(resolve(out, 'crash-matrix.md'), md)
console.log(md)
process.exit(all && unitOk ? 0 : 1)
