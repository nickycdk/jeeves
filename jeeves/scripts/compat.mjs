// Compatibility matrix (ST-8.3, AC-22): for each Claude Code version, install it from npm into <work>/<version>
// (never globally), copy the plugin there, run `claude plugin validate --strict` and `claude plugin test` with an
// empty, logged-out CLAUDE_CONFIG_DIR (no model calls, no account), and write docs/compatibility.md.
//
//   node scripts/compat.mjs <work dir> <version> [<version> ...]
import { execFileSync, spawnSync } from 'node:child_process'
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PLUGIN = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const [work, ...versions] = process.argv.slice(2)
if (!work || !versions.length) { console.error('usage: node scripts/compat.mjs <work dir> <version> [<version> ...]'); process.exit(2) }
if ((resolve(work) + '/').startsWith(PLUGIN + '/')) { console.error('compat: the work dir must be outside the plugin folder (it copies the plugin into it)'); process.exit(2) }
const MIN = /MIN_VERSION = '([^']+)'/.exec(readFileSync(join(PLUGIN, 'src/core/probe.ts'), 'utf8'))[1]

const rows = []
for (const v of versions) {
  const dir = resolve(work, v), bin = join(dir, 'node_modules/.bin/claude'), copy = join(dir, 'plugin'), cfg = join(dir, 'config')
  if (!existsSync(bin)) execFileSync('npm', ['install', '--prefix', dir, '--no-audit', '--no-fund', `@anthropic-ai/claude-code@${v}`], { stdio: 'inherit' })
  rmSync(copy, { recursive: true, force: true })
  cpSync(PLUGIN, copy, { recursive: true, filter: p => !/\/(node_modules|\.claude-plugin\/types)(\/|$)/.test(p) })
  mkdirSync(cfg, { recursive: true })
  const env = { ...Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^(CLAUDE|ANTHROPIC)/.test(k))), CLAUDE_CONFIG_DIR: cfg }
  const run = args => spawnSync(bin, args, { cwd: copy, env, encoding: 'utf8', timeout: 300_000 })
  const validate = run(['plugin', 'validate', '.', '--strict'])
  const test = run(['plugin', 'test', '.'])
  const out = test.stdout + test.stderr
  const n = re => Number(re.exec(out)?.[1] ?? NaN)
  const why = (validate.stdout + validate.stderr).split('\n').find(l => l.includes('❯'))?.replaceAll(copy, '<plugin>').replace(/^\s*❯\s*/, '').replaceAll('`', "'") ?? ''
  rows.push({ v, why, validate: validate.status === 0, pass: n(/^\s*(\d+) pass/m), fail: n(/^\s*(\d+) fail/m), ok: test.status === 0 })
  console.log(v, rows.at(-1))
}

const plugin = JSON.parse(readFileSync(join(PLUGIN, '.claude-plugin/plugin.json'), 'utf8')).version
writeFileSync(join(PLUGIN, 'docs/compatibility.md'), [
  '# Compatibility',
  '',
  `Generated by \`node scripts/compat.mjs\` on ${new Date().toISOString().slice(0, 10)} for Jeeves ${plugin} on ${execFileSync('uname', ['-sr'], { encoding: 'utf8' }).trim()}.`,
  `Each version was installed from npm into a scratch folder and ran \`claude plugin validate . --strict\` and \`claude plugin test .\` (the engine's test kit: no model calls, logged out).`,
  '',
  `**Supported:** Claude Code ${MIN} or later (\`MIN_VERSION\` in \`src/core/probe.ts\`); older versions run Jeeves as unsupported (it stays off and says which version it needs). A passing row below for an older version means only that the mod loads and its tests pass in that version's test kit; rotation in a live session was verified on ${MIN} only. On Claude accounts in a Team organization Jeeves runs in turn mode (README, Requirements); the mod tests run in that mode too (\`npm run test:mod:turn\`).`,
  '',
  '| Claude Code | validate --strict | mod tests | supported |',
  '|---|---|---|---|',
  ...rows.map(r => `| ${r.v} | ${r.validate ? 'pass' : 'FAIL'} | ${r.ok ? `pass (${r.pass})` : Number.isNaN(r.pass) ? 'FAIL (no test summary: crashed or timed out)' : `FAIL (${r.pass} pass, ${r.fail} fail)`} | ${cmp(r.v, MIN) >= 0 ? 'yes' : 'no (below minimum)'} |`),
  '',
  ...rows.filter(r => !r.validate).flatMap(r => [`- ${r.v}: validate says \`${r.why}\``]),
  '',
].join('\n'))

function cmp(a, b) {
  const x = a.split('.').map(Number), y = b.split('.').map(Number)
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]
  return 0
}
